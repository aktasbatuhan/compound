"""Write the tokenizer study's tables as Markdown, from the committed JSON files.

Every number in a write-up about the study should come from here, so it can be
traced to a file and regenerated:

    python3 scripts/report_tokenizer_premium.py \\
        benchmarks/tokenizers/flores-premium-2026-10-31.json \\
        benchmarks/prices/openrouter-2026-10-31.json > benchmarks/tokenizers/README.md
"""

from __future__ import annotations

import json
import sys

#: OpenRouter model id -> key in the study. Same weights share a tokenizer.
PRICED = {
    "deepseek/deepseek-v4.1-flash": "deepseek-ai/DeepSeek-V4.1-Flash",
    "deepseek/deepseek-v4-pro": "deepseek-ai/DeepSeek-V4-Pro",
    "z-ai/glm-5.3": "zai-org/GLM-5.3",
    "z-ai/glm-5.3-flash": "zai-org/GLM-5.3-Flash",
    "qwen/qwen3.8-flash": "Qwen/Qwen3.8-Flash-Next",
    "qwen/qwen3.8-27b": "Qwen/Qwen3.8-27B",
    "mistralai/mistral-small-2603": "mistralai/Mistral-Small-4-119B-2603",
    "mistralai/mistral-large-4-0": "mistralai/Mistral-Large-4-1T-A52B",
    "openai/gpt-oss-120b": "openai/gpt-oss-120b",
    "google/gemma-4-31b-it": "google/gemma-4-31B-it",
    "openai/gpt-6-sol": "openai:gpt-6-sol",
    "openai/gpt-5.4-mini": "openai:gpt-5.4-mini",
}
REFERENCE = "tiktoken:o200k_base"
LANG_NAMES = {"tr": "Turkish", "ar": "Arabic", "az": "Azerbaijani", "kk": "Kazakh",
              "uz": "Uzbek"}


def main(study_path: str, prices_path: str) -> str:
    study = json.load(open(study_path))
    prices = json.load(open(prices_path))
    models = study["models"]
    corpus = study["corpus"]
    out = [
        "# Tokenizer premium",
        "",
        f"Measured {study['measured_at']} on {corpus['dataset']} {corpus['split']} "
        f"(revision `{corpus['revision'][:10]}`, {corpus['license']}): "
        f"{corpus['sentences']:,} sentences with the same meaning in every language. "
        f"Prices from the OpenRouter snapshot of "
        f"{prices['fetched_at_iso'][:10]}. Generated by "
        "`scripts/report_tokenizer_premium.py`; do not edit by hand.",
        "",
        "## Same meaning, how many tokens",
        "",
        "Premium is tokens in the language divided by tokens for the same English "
        "sentences on the same tokenizer, with a 95% bootstrap interval.",
        "",
        "| Tokenizer | English tokens | Turkish tokens | Turkish premium | "
        + " | ".join(LANG_NAMES[x] for x in ("ar", "az", "kk", "uz")) + " |",
        "|---|---:|---:|---|" + "---:|" * 4,
    ]
    order = sorted(models.items(), key=lambda kv: kv[1]["premium_vs_en"]["tr"]["ratio"])
    for name, r in order:
        tr = r["premium_vs_en"]["tr"]
        rest = " | ".join(
            f"{r['premium_vs_en'][x]['ratio']:.2f}" if x in r["premium_vs_en"] else "not run"
            for x in ("ar", "az", "kk", "uz")
        )
        out.append(
            f"| `{name}` | {r['tokens']['en']:,} | {r['tokens']['tr']:,} | "
            f"{tr['ratio']:.2f} ({tr['ci95'][0]:.2f} to {tr['ci95'][1]:.2f}) | {rest} |"
        )
    ref_en = models[REFERENCE]["tokens"]["en"]
    out += [
        "",
        "## What a million tokens of meaning costs",
        "",
        "The listed price is per token. The effective price is per the same amount of "
        f"meaning, taking `{REFERENCE}` on English ({ref_en:,} tokens) as one unit: "
        "listed price times the model's tokens for the text divided by that unit. "
        "USD per million, from each model's default OpenRouter listing.",
        "",
        "| Model | Listed input | Listed output | Turkish input | Turkish output | "
        "English output |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    rows = []
    for mid, key in PRICED.items():
        card, r = prices["models"][mid], models[key]
        f_tr, f_en = r["tokens"]["tr"] / ref_en, r["tokens"]["en"] / ref_en
        rows.append((card["completion"] * f_tr, mid, card, f_tr, f_en))
    for _, mid, card, f_tr, f_en in sorted(rows, key=lambda x: x[0]):
        out.append(
            f"| `{mid}` | {card['prompt']:.3f} | {card['completion']:.3f} | "
            f"{card['prompt'] * f_tr:.3f} | {card['completion'] * f_tr:.3f} | "
            f"{card['completion'] * f_en:.3f} |"
        )
    out += [
        "",
        "## Limits",
        "",
        "- FLORES sentences are news and encyclopedia prose. Chat, legal and code-mixed "
        "text may tokenize differently.",
        "- Claude and Gemini are not measured yet; their tokenizers are not public and "
        "the paid count through OpenRouter was not run.",
        "- Token cost is not quality. A model that needs fewer tokens can still give "
        "worse Turkish answers.",
        f"- Paid calls for this study: ${study['paid_usd']:.2f}. OpenAI counts came from "
        "its free input-token endpoint.",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(main(sys.argv[1], sys.argv[2]))
